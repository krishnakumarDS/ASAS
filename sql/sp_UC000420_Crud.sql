CREATE OR ALTER PROCEDURE [dbo].[sp_UC000420_Crud]
  @entity    nvarchar(50),
  @operation nvarchar(20),
  @json      nvarchar(max) = N'{}'
-- WITH EXECUTE AS OWNER
AS
BEGIN
  SET NOCOUNT ON;
  SET XACT_ABORT ON;

  DECLARE @msg nvarchar(2048);

  IF @entity IS NULL OR @operation IS NULL THROW 51001, 'entity and operation are required', 1;
  SET @json = ISNULL(NULLIF(LTRIM(RTRIM(@json)), N''), N'{}');
  IF ISJSON(@json) = 0 OR LEFT(LTRIM(@json), 1) <> N'{' THROW 51002, 'json must be a JSON object', 1;

  /* ---------- 1. which table ---------- */
  DECLARE @table sysname = CASE @entity
      WHEN N'consultant'            THEN N'UC000420_Consultants'
      WHEN N'developer'             THEN N'UC000420_Developers'
      WHEN N'project'               THEN N'UC000420_MasterProjectTable'
      WHEN N'plot'                  THEN N'UC000420_Plots'
      WHEN N'substation'            THEN N'UC000420_Substations'
      WHEN N'consultantIssue'       THEN N'UC000420_ConsultantIssues'
      WHEN N'developerIssue'        THEN N'UC000420_DeveloperIssues'
      WHEN N'existingKVSS'          THEN N'UC000420_ExistingKVSS'
      WHEN N'projectIssue'          THEN N'UC000420_Issues'
      WHEN N'issueFile'             THEN N'UC000420_IssuesFileLink'
      WHEN N'substationLimitLookup' THEN N'UC000420_LookUp_Substation_Limits_TCL'
      WHEN N'ppr'                   THEN N'UC000420_PPR'
      WHEN N'pprFile'               THEN N'UC000420_PPRFileLink'
      WHEN N'projectConsultant'     THEN N'UC000420_Project_Consultant_Link'
      WHEN N'projectHistory'        THEN N'UC000420_ProjectHistory'
      WHEN N'projectHistoryFile'    THEN N'UC000420_ProjectHistoryFileLink'
      WHEN N'projectFutureYear'     THEN N'UC000420_ProjectsFutureYears'
      WHEN N'projectRemark'         THEN N'UC000420_ProjectsRemarks'
      WHEN N'substationLimit'       THEN N'UC000420_Substation_Limits_TCL'
      ELSE NULL END;
  IF @table IS NULL THROW 51003, 'Unknown entity', 1;
  IF @operation NOT IN (N'create', N'update', N'setActive', N'delete', N'get', N'list', N'createMany', N'setActiveMany', N'deleteMany', N'columns') THROW 51004, 'Unknown operation', 1;

  DECLARE @sqlTable nvarchar(300) = N'dbo.' + QUOTENAME(@table);
  DECLARE @obj int = OBJECT_ID(@sqlTable);
  IF @obj IS NULL THROW 51005, 'The table does not exist in this database', 1;

  /* ---------- 2. primary key, actor, id ---------- */
  DECLARE @pk sysname = (
    SELECT TOP (1) c.name
    FROM sys.indexes i
    JOIN sys.index_columns ic ON ic.object_id = i.object_id AND ic.index_id = i.index_id
    JOIN sys.columns c        ON c.object_id = ic.object_id AND c.column_id = ic.column_id
    WHERE i.object_id = @obj AND i.is_primary_key = 1
    ORDER BY ic.key_ordinal);
  IF @pk IS NULL SET @pk = (SELECT name FROM sys.columns WHERE object_id = @obj AND column_id = 1);
  IF @entity = N'project' SET @pk = N'MaalemDubaiRef';  -- projects are addressed by their Maalem Dubai reference (id = MP-xxxxx-xxx)

  DECLARE @user nvarchar(255) = ISNULL(NULLIF(JSON_VALUE(@json, '$.user'), N''), ORIGINAL_LOGIN());
  DECLARE @id   nvarchar(255) = JSON_VALUE(@json, '$.id');

  -- A numeric key (RowID, DeveloperID, ...) must be given as a number: say so clearly instead of failing inside SQL.
  DECLARE @pkNumeric bit = CASE WHEN EXISTS (SELECT 1 FROM sys.columns c JOIN sys.types ty ON ty.user_type_id = c.user_type_id
                                              WHERE c.object_id = @obj AND c.name = @pk AND ty.name IN (N'int', N'bigint', N'smallint', N'tinyint', N'decimal', N'numeric')) THEN 1 ELSE 0 END;
  IF @id IS NOT NULL AND @pkNumeric = 1 AND TRY_CAST(@id AS bigint) IS NULL
  BEGIN
    SET @msg = CONCAT(N'id must be a number (the ', @pk, N' of the row), not "', @id, N'"');
    THROW 51018, @msg, 1;
  END
  IF @operation IN (N'setActiveMany', N'deleteMany') AND @pkNumeric = 1
     AND EXISTS (SELECT 1 FROM OPENJSON(@json, '$.ids') WITH (v nvarchar(255) '$') WHERE TRY_CAST(v AS bigint) IS NULL)
    THROW 51018, 'Every id must be a number', 1;

  /* ---------- 3. columns that may be written / read ---------- */
  DECLARE @cols TABLE (name sysname PRIMARY KEY, is_required bit, is_pk bit, is_bit bit, jkey nvarchar(128) NULL);
  INSERT @cols (name, is_required, is_pk, is_bit)
  SELECT c.name,
         CASE WHEN c.is_nullable = 0 AND c.default_object_id = 0 THEN 1 ELSE 0 END,
         CASE WHEN c.name = @pk THEN 1 ELSE 0 END,
         CASE WHEN ty.name = N'bit' THEN 1 ELSE 0 END
  FROM sys.columns c
  JOIN sys.types ty ON ty.user_type_id = c.user_type_id
  WHERE c.object_id = @obj AND c.is_identity = 0 AND c.is_computed = 0
    AND ty.name NOT IN (N'timestamp', N'rowversion', N'varbinary', N'binary', N'image', N'geography', N'geometry', N'hierarchyid', N'sql_variant', N'xml')
    AND c.name NOT IN (N'created_at', N'created_by', N'updated_at', N'updated_by',
                       N'ObjectKey', N'RobotName', N'ExecutionId', N'FirstExtracted', N'LastExtracted', N'ExtractedInLastRun', N'LastUpdated');

  DECLARE @hasActive    bit = CASE WHEN EXISTS (SELECT 1 FROM sys.columns WHERE object_id = @obj AND name = N'IsActive')   THEN 1 ELSE 0 END;
  DECLARE @hasCreatedAt bit = CASE WHEN EXISTS (SELECT 1 FROM sys.columns WHERE object_id = @obj AND name = N'created_at') THEN 1 ELSE 0 END;
  DECLARE @hasCreatedBy bit = CASE WHEN EXISTS (SELECT 1 FROM sys.columns WHERE object_id = @obj AND name = N'created_by') THEN 1 ELSE 0 END;
  DECLARE @hasUpdatedAt bit = CASE WHEN EXISTS (SELECT 1 FROM sys.columns WHERE object_id = @obj AND name = N'updated_at') THEN 1 ELSE 0 END;
  DECLARE @hasUpdatedBy bit = CASE WHEN EXISTS (SELECT 1 FROM sys.columns WHERE object_id = @obj AND name = N'updated_by') THEN 1 ELSE 0 END;

  /* ---------- 4. which fields the caller sent ---------- */
  DECLARE @keys TABLE ([key] nvarchar(128));
  INSERT @keys ([key])
  SELECT [key] FROM OPENJSON(@json)
  WHERE [key] NOT IN (N'id', N'ids', N'rows', N'user', N'page', N'pageSize', N'pageNumber', N'orderBy', N'sort');
  IF @operation = N'createMany'
  BEGIN
    IF JSON_QUERY(@json, '$.rows') IS NULL THROW 51016, 'rows must be a non-empty array of objects', 1;
    INSERT @keys ([key])
    SELECT DISTINCT k.[key] FROM OPENJSON(@json, '$.rows') r CROSS APPLY OPENJSON(r.value) k;
  END

  IF EXISTS (SELECT 1 FROM @keys WHERE [key] LIKE N'%[^A-Za-z0-9_]%') THROW 51006, 'Field names may contain only letters, digits and underscore', 1;

  UPDATE c SET c.jkey = k.[key] FROM @cols c JOIN @keys k ON LOWER(k.[key]) = LOWER(c.name);

  DECLARE @unknown nvarchar(max) = STUFF((SELECT N', ' + k.[key] FROM @keys k
      WHERE NOT EXISTS (SELECT 1 FROM @cols c WHERE c.jkey = k.[key]) FOR XML PATH(N''), TYPE).value('.', 'nvarchar(max)'), 1, 2, N'');
  DECLARE @missing nvarchar(max) = STUFF((SELECT N', ' + c.name FROM @cols c
      WHERE c.is_required = 1 AND c.jkey IS NULL AND c.name <> N'IsActive' FOR XML PATH(N''), TYPE).value('.', 'nvarchar(max)'), 1, 2, N'');

  /* ---------- 5. text pieces built only from sys.columns names and the matched JSON keys ---------- */
  DECLARE @selList nvarchar(max) = STUFF((SELECT N', ' + QUOTENAME(c.name)
      FROM sys.columns c JOIN sys.types ty ON ty.user_type_id = c.user_type_id
      WHERE c.object_id = @obj
        AND ty.name NOT IN (N'timestamp', N'rowversion', N'varbinary', N'binary', N'image', N'geography', N'geometry', N'hierarchyid', N'sql_variant', N'xml')
        AND c.name NOT IN (N'ObjectKey', N'RobotName', N'ExecutionId', N'FirstExtracted', N'LastExtracted', N'ExtractedInLastRun', N'LastUpdated')
      ORDER BY c.column_id FOR XML PATH(N''), TYPE).value('.', 'nvarchar(max)'), 1, 2, N'');
  DECLARE @colList nvarchar(max) = STUFF((SELECT N', ' + QUOTENAME(c.name) FROM @cols c WHERE c.jkey IS NOT NULL FOR XML PATH(N''), TYPE).value('.', 'nvarchar(max)'), 1, 2, N'');
  DECLARE @valList nvarchar(max) = STUFF((SELECT N', ' + CASE WHEN c.is_bit = 1 THEN N'CASE WHEN LOWER(j.' + QUOTENAME(c.name) + N') IN (N''yes'', N''y'', N''true'', N''1'') THEN CAST(1 AS bit) WHEN LOWER(j.' + QUOTENAME(c.name) + N') IN (N''no'', N''n'', N''false'', N''0'') THEN CAST(0 AS bit) END' ELSE N'j.' + QUOTENAME(c.name) END FROM @cols c WHERE c.jkey IS NOT NULL FOR XML PATH(N''), TYPE).value('.', 'nvarchar(max)'), 1, 2, N'');
  DECLARE @setList nvarchar(max) = STUFF((SELECT N', t.' + QUOTENAME(c.name) + N' = ' + CASE WHEN c.is_bit = 1 THEN N'CASE WHEN LOWER(j.' + QUOTENAME(c.name) + N') IN (N''yes'', N''y'', N''true'', N''1'') THEN CAST(1 AS bit) WHEN LOWER(j.' + QUOTENAME(c.name) + N') IN (N''no'', N''n'', N''false'', N''0'') THEN CAST(0 AS bit) END' ELSE N'j.' + QUOTENAME(c.name) END FROM @cols c WHERE c.jkey IS NOT NULL AND c.is_pk = 0 FOR XML PATH(N''), TYPE).value('.', 'nvarchar(max)'), 1, 2, N'');
  DECLARE @withList nvarchar(max) = STUFF((SELECT N', ' + QUOTENAME(c.name) + N' nvarchar(max) ''$."' + c.jkey + N'"''' FROM @cols c WHERE c.jkey IS NOT NULL FOR XML PATH(N''), TYPE).value('.', 'nvarchar(max)'), 1, 2, N'');

  DECLARE @sql nvarchar(max), @rows int = 0, @active bit, @n int, @srcPath nvarchar(20) = N'$';
  DECLARE @pageSize int = ISNULL(TRY_CAST(JSON_VALUE(@json, '$.pageSize') AS int), 50);
  DECLARE @pageNumber int = ISNULL(TRY_CAST(JSON_VALUE(@json, '$.pageNumber') AS int), 1);
  DECLARE @extraCols nvarchar(max) = N'', @extraVals nvarchar(max) = N'', @extraSet nvarchar(max) = N'', @where nvarchar(max) = N'';

  /* ---------- 6. reads ---------- */
  IF @operation = N'columns'
  BEGIN
    SELECT c.name AS Name, ty.name AS DataType, c.max_length AS MaxLength, c.is_nullable AS Nullable, c.is_identity AS IsIdentity
    FROM sys.columns c JOIN sys.types ty ON ty.user_type_id = c.user_type_id
    WHERE c.object_id = @obj ORDER BY c.column_id;
    RETURN;
  END

  IF @operation = N'get'
  BEGIN
    IF @id IS NULL THROW 51010, 'id is required', 1;
    SET @sql = N'SELECT ' + @selList + N' FROM ' + @sqlTable + N' WHERE ' + QUOTENAME(@pk) + N' = @id';
    EXEC sys.sp_executesql @sql, N'@id nvarchar(255)', @id = @id;
    RETURN;
  END

  IF @operation = N'list'
  BEGIN
    IF @pageSize NOT BETWEEN 1 AND 500 OR @pageNumber < 1 THROW 51015, 'pageSize must be 1-500 and pageNumber 1 or more', 1;
    SET @active = TRY_CAST(JSON_VALUE(@json, '$.isActive') AS bit);
    IF @hasActive = 1 AND @active IS NOT NULL SET @where = N' WHERE [IsActive] = @active';
    DECLARE @skip int = (@pageNumber - 1) * @pageSize;
    SET @sql = N'SELECT ' + @selList + N' FROM ' + @sqlTable + @where + N' ORDER BY ' + QUOTENAME(@pk)
             + N' OFFSET @skip ROWS FETCH NEXT @take ROWS ONLY; SELECT COUNT(*) AS TotalCount FROM ' + @sqlTable + @where + N';';
    EXEC sys.sp_executesql @sql, N'@active bit, @skip int, @take int', @active = @active, @skip = @skip, @take = @pageSize;
    RETURN;
  END

  /* ---------- 7. writes (one transaction) ---------- */
  CREATE TABLE #ids (Id nvarchar(255));

  BEGIN TRY
    BEGIN TRAN;

    IF @operation IN (N'create', N'createMany')
    BEGIN
      IF @operation = N'createMany'
      BEGIN
        SET @srcPath = N'$.rows';
        SET @n = (SELECT COUNT(*) FROM OPENJSON(@json, '$.rows'));
        IF @n = 0 THROW 51016, 'rows must be a non-empty array of objects', 1;
        IF @n > 1000 THROW 51017, 'At most 1000 rows per call', 1;
      END
      IF @unknown IS NOT NULL
      BEGIN
        SET @msg = CONCAT(N'Unknown field(s) for ', @entity, N': ', @unknown);
        THROW 51007, @msg, 1;
      END
      IF @colList IS NULL THROW 51009, 'No fields were supplied', 1;
      IF @missing IS NOT NULL
      BEGIN
        SET @msg = CONCAT(N'Missing required field(s) for ', @entity, N': ', @missing);
        THROW 51008, @msg, 1;
      END

      IF @hasActive = 1 AND NOT EXISTS (SELECT 1 FROM @cols WHERE name = N'IsActive' AND jkey IS NOT NULL)
        SELECT @extraCols += N', [IsActive]', @extraVals += N', 1';
      IF @hasCreatedAt = 1 SELECT @extraCols += N', [created_at]', @extraVals += N', SYSUTCDATETIME()';
      IF @hasCreatedBy = 1 SELECT @extraCols += N', [created_by]', @extraVals += N', @user';

      SET @sql = N'INSERT INTO ' + @sqlTable + N' (' + @colList + @extraCols + N') OUTPUT CAST(INSERTED.' + QUOTENAME(@pk) + N' AS nvarchar(255)) INTO #ids (Id) '
               + N'SELECT ' + @valList + @extraVals + N' FROM OPENJSON(@json, ''' + @srcPath + N''') WITH (' + @withList + N') j;';
      EXEC sys.sp_executesql @sql, N'@json nvarchar(max), @user nvarchar(255)', @json = @json, @user = @user;
      SELECT Id FROM #ids;
    END

    ELSE IF @operation = N'update'
    BEGIN
      IF @id IS NULL THROW 51010, 'id is required', 1;
      IF @unknown IS NOT NULL
      BEGIN
        SET @msg = CONCAT(N'Unknown field(s) for ', @entity, N': ', @unknown);
        THROW 51007, @msg, 1;
      END
      IF @setList IS NULL THROW 51011, 'Nothing to update', 1;

      IF @hasUpdatedAt = 1 SET @extraSet += N', t.[updated_at] = SYSUTCDATETIME()';
      IF @hasUpdatedBy = 1 SET @extraSet += N', t.[updated_by] = @user';

      SET @sql = N'UPDATE t SET ' + @setList + @extraSet + N' FROM ' + @sqlTable + N' t CROSS JOIN OPENJSON(@json) WITH (' + @withList + N') j '
               + N'WHERE t.' + QUOTENAME(@pk) + N' = @id; SET @rows = @@ROWCOUNT;';
      EXEC sys.sp_executesql @sql, N'@json nvarchar(max), @user nvarchar(255), @id nvarchar(255), @rows int OUTPUT', @json = @json, @user = @user, @id = @id, @rows = @rows OUTPUT;
      IF @rows = 0 THROW 51012, 'No record matches that id', 1;
      SELECT @id AS Id, @rows AS RowsAffected;
    END

    ELSE IF @operation IN (N'setActiveMany', N'deleteMany')
    BEGIN
      SET @n = (SELECT COUNT(*) FROM OPENJSON(@json, '$.ids'));
      IF @n = 0 THROW 51016, 'ids must be a non-empty array', 1;
      IF @n > 1000 THROW 51017, 'At most 1000 ids per call', 1;

      IF @operation = N'deleteMany' AND @hasActive = 0
      BEGIN
        /* no IsActive column: remove the rows */
        SET @sql = N'DELETE t FROM ' + @sqlTable + N' t JOIN OPENJSON(@json, ''$.ids'') WITH (v nvarchar(255) ''$'') x ON t.' + QUOTENAME(@pk) + N' = x.v; SET @rows = @@ROWCOUNT;';
        EXEC sys.sp_executesql @sql, N'@json nvarchar(max), @rows int OUTPUT', @json = @json, @rows = @rows OUTPUT;
      END
      ELSE
      BEGIN
        IF @hasActive = 0 THROW 51013, 'This table has no IsActive column', 1;
        SET @active = CASE WHEN @operation = N'deleteMany' THEN 0 ELSE TRY_CAST(JSON_VALUE(@json, '$.isActive') AS bit) END;
        IF @active IS NULL THROW 51014, 'isActive (true or false) is required', 1;
        IF @hasUpdatedAt = 1 SET @extraSet += N', [updated_at] = SYSUTCDATETIME()';
        IF @hasUpdatedBy = 1 SET @extraSet += N', [updated_by] = @user';
        SET @sql = N'UPDATE t SET [IsActive] = @active' + @extraSet + N' FROM ' + @sqlTable + N' t JOIN OPENJSON(@json, ''$.ids'') WITH (v nvarchar(255) ''$'') x ON t.' + QUOTENAME(@pk) + N' = x.v; SET @rows = @@ROWCOUNT;';
        EXEC sys.sp_executesql @sql, N'@json nvarchar(max), @active bit, @user nvarchar(255), @rows int OUTPUT', @json = @json, @active = @active, @user = @user, @rows = @rows OUTPUT;
      END
      IF @rows = 0 THROW 51012, 'No record matches those ids', 1;
      SELECT @n AS Requested, @rows AS RowsAffected;
    END

    ELSE IF @operation = N'setActive' OR (@operation = N'delete' AND @hasActive = 1)
    BEGIN
      IF @hasActive = 0 THROW 51013, 'This table has no IsActive column', 1;
      IF @id IS NULL THROW 51010, 'id is required', 1;
      SET @active = CASE WHEN @operation = N'delete' THEN 0 ELSE TRY_CAST(JSON_VALUE(@json, '$.isActive') AS bit) END;
      IF @active IS NULL THROW 51014, 'isActive (true or false) is required', 1;

      IF @hasUpdatedAt = 1 SET @extraSet += N', [updated_at] = SYSUTCDATETIME()';
      IF @hasUpdatedBy = 1 SET @extraSet += N', [updated_by] = @user';

      SET @sql = N'UPDATE ' + @sqlTable + N' SET [IsActive] = @active' + @extraSet + N' WHERE ' + QUOTENAME(@pk) + N' = @id; SET @rows = @@ROWCOUNT;';
      EXEC sys.sp_executesql @sql, N'@active bit, @user nvarchar(255), @id nvarchar(255), @rows int OUTPUT', @active = @active, @user = @user, @id = @id, @rows = @rows OUTPUT;
      IF @rows = 0 THROW 51012, 'No record matches that id', 1;
      SELECT @id AS Id, @rows AS RowsAffected;
    END

    ELSE  /* delete on a table without IsActive: remove the row */
    BEGIN
      IF @id IS NULL THROW 51010, 'id is required', 1;
      SET @sql = N'DELETE FROM ' + @sqlTable + N' WHERE ' + QUOTENAME(@pk) + N' = @id; SET @rows = @@ROWCOUNT;';
      EXEC sys.sp_executesql @sql, N'@id nvarchar(255), @rows int OUTPUT', @id = @id, @rows = @rows OUTPUT;
      IF @rows = 0 THROW 51012, 'No record matches that id', 1;
      SELECT @id AS Id, @rows AS RowsAffected;
    END

    COMMIT;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK;
    THROW;
  END CATCH
END
GO

