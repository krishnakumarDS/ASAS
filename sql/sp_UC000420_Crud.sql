 /*
  sp_UC000420_Crud  --  one procedure for create / update / enable-disable / delete / get / list on the 19 ASAS tables.

  EXEC dbo.sp_UC000420_Crud @entity, @operation, @json

  @entity (allow-listed; anything else is rejected)
    consultant, developer, project, plot, substation, consultantIssue, developerIssue, existingKVSS, projectIssue, issueFile,
    substationLimitLookup, ppr, pprFile, projectConsultant, projectHistory, projectHistoryFile, projectFutureYear,
    projectRemark, substationLimit

  @operation
    create     insert one row.             {"developerName":"…","developerURL":"…","user":"jane"}            -> returns Id
    update     change the given fields.    {"id":12,"developerURL":"https://…","user":"jane"}                -> returns Id, RowsAffected
    setActive  show / hide a row.          {"id":12,"isActive":false,"user":"jane"}                          -> returns Id, RowsAffected
    delete     soft delete (IsActive = 0) when the table has IsActive, otherwise removes the row.  {"id":12,"user":"jane"}
    get        one row by key.             {"id":12}
    list       a page of rows.             {"pageSize":50,"pageNumber":1,"isActive":true}                    -> rows, then TotalCount
    columns    the table's columns and data types (read-only; used by the importer).  {}        -> Name, DataType, MaxLength, Nullable, IsIdentity
    createMany    insert many rows in ONE call (bulk upload).  {"rows":[{…},{…}],"user":"jane"}              -> one Id per row
    setActiveMany show / hide many rows in ONE call.           {"ids":[1,2,3],"isActive":false,"user":"jane"} -> Requested, RowsAffected
    deleteMany    soft delete many rows in ONE call.           {"ids":[1,2,3],"user":"jane"}                 -> Requested, RowsAffected
    The Many operations take at most 1000 rows / ids per call and all succeed or all roll back.

  JSON keys are the column names, any letter case (developerName = DeveloperName). "id" is the value of the table's primary key.
  "user" is who is making the change (written to created_by / updated_by); it defaults to the connection's login.

  How it stays safe
    - Table and column names come only from the allow-list above and from sys.columns, never from the caller.
    - Values are never pasted into SQL text: they are read from the JSON by OPENJSON inside the statement.
    - Unknown fields, missing required columns and unknown entities / operations are rejected with a clear message.
    - Binary columns (e.g. ConsultantImage) and the robot / extraction columns (ObjectKey, RobotName, ExecutionId,
      FirstExtracted, LastExtracted, ExtractedInLastRun, LastUpdated) are not writable from here; they are not returned either.
    - created_at / updated_at are set to SYSUTCDATETIME() (UTC); change to SYSDATETIME() if the table stores local time.
    - Writes run in a transaction and roll back on any error.

  Assumptions to confirm (tables.md lists column names only):
    - The first column of each table is its primary key, or the table has a real primary key (a real one is used first).
      The project table's key is MaalemDubaiRef when it has no primary key.
    - Identity keys are generated by SQL Server; a key that is not an identity (e.g. MaalemDubaiRef) must be supplied on create.
    - Values arrive as text and SQL Server converts them to the column type (numbers, dates). bit columns accept yes / no / true / false / 1 / 0.
    - A project is identified by MaalemDubaiRef (id = "MP-xxxxx-xxx"), whatever the table's primary key is.

  Permissions: the connection's login needs EXECUTE on this procedure AND INSERT / UPDATE / DELETE / SELECT on the tables,
  because the statements are built dynamically. To avoid granting table rights, add WITH EXECUTE AS OWNER below (this lets anyone
  with EXECUTE write all 19 tables, so decide deliberately).

  Error numbers (THROW): 51001 entity / operation missing, 51002 json is not an object, 51003 unknown entity, 51004 unknown operation,
  51005 table not found, 51006 bad field name, 51007 unknown field, 51008 missing required field, 51009 no fields supplied,
  51010 id required, 51011 nothing to update, 51012 no record matches, 51013 table has no IsActive, 51014 isActive required,
  51015 bad paging, 51016 rows / ids is empty or not an array, 51017 more than 1000 rows / ids,
  51018 id is not a number although the table's key is numeric.
*/
